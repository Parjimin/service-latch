//! One writer, no heartbeat, at most two 256 KiB files in the installed log dir.
use std::fs::{self, File, OpenOptions};
use std::io::{self, Write};
use std::path::{Path, PathBuf};
use std::time::{Instant, SystemTime, UNIX_EPOCH};

pub const MAX_LOG_BYTES: u64 = 256 * 1024;

pub struct EventLog {
    directory: PathBuf,
    file: Option<File>,
    limit: u64,
    bytes: u64,
    started: Instant,
    run: String,
}

impl EventLog {
    pub fn open(directory: &Path) -> io::Result<Self> {
        Self::with_limit(directory, MAX_LOG_BYTES)
    }

    fn with_limit(directory: &Path, limit: u64) -> io::Result<Self> {
        // Never create a directory from inside the service. Installation owns it.
        let metadata = fs::symlink_metadata(directory)?;
        if !metadata.is_dir() || metadata.file_type().is_symlink() {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "log directory is not a real directory",
            ));
        }
        let file = Self::open_file(directory)?;
        let bytes = file.metadata()?.len();
        if bytes > limit {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                "existing log exceeds limit; preserve it for inspection",
            ));
        }
        Ok(Self {
            directory: directory.to_owned(),
            file: Some(file),
            limit,
            bytes,
            started: Instant::now(),
            run: format!("{}-{}", unix_millis(), std::process::id()),
        })
    }

    fn open_file(directory: &Path) -> io::Result<File> {
        OpenOptions::new()
            .create(true)
            .append(true)
            .open(directory.join("events.log"))
    }

    /// Event names and details are fixed strings/numeric codes generated by code.
    pub fn record(&mut self, event: &str, code: u32) -> io::Result<()> {
        if event.is_empty()
            || event.len() > 64
            || !event
                .bytes()
                .all(|c| c.is_ascii_alphanumeric() || c == b'_')
        {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "invalid event name",
            ));
        }
        let line = format!(
            "unix_ms={} elapsed_ms={} run={} pid={} event={} code={}\n",
            unix_millis(),
            self.started.elapsed().as_millis(),
            self.run,
            std::process::id(),
            event,
            code
        );
        if line.len() as u64 > self.limit {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "event exceeds log limit",
            ));
        }
        if self.bytes.saturating_add(line.len() as u64) > self.limit {
            self.file.take(); // Close before rename (also works on Windows).
            match fs::remove_file(self.directory.join("events.previous.log")) {
                Ok(()) => {}
                Err(e) if e.kind() == io::ErrorKind::NotFound => {}
                Err(e) => return Err(e),
            }
            fs::rename(
                self.directory.join("events.log"),
                self.directory.join("events.previous.log"),
            )?;
            self.file = Some(Self::open_file(&self.directory)?);
            self.bytes = 0;
        }
        let file = self
            .file
            .as_mut()
            .ok_or_else(|| io::Error::other("log file unavailable"))?;
        file.write_all(line.as_bytes())?;
        // Only lifecycle boundaries are logged; persist them, then sleep without I/O.
        file.sync_data()?;
        self.bytes += line.len() as u64;
        Ok(())
    }
}

fn unix_millis() -> u128 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::atomic::{AtomicUsize, Ordering};
    static NEXT: AtomicUsize = AtomicUsize::new(0);
    struct Temp(PathBuf);
    impl Temp {
        fn new() -> Self {
            let p = std::env::temp_dir().join(format!(
                "sl-poc1a-{}-{}-{}",
                std::process::id(),
                unix_millis(),
                NEXT.fetch_add(1, Ordering::Relaxed)
            ));
            fs::create_dir(&p).unwrap();
            Self(p)
        }
    }
    impl Drop for Temp {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    #[test]
    fn missing_directory_is_not_created() {
        let temp = Temp::new();
        let missing = temp.0.join("missing");
        assert!(EventLog::open(&missing).is_err());
        assert!(!missing.exists());
    }

    #[test]
    fn rotation_and_reopening_keep_two_bounded_files() {
        let temp = Temp::new();
        for _ in 0..3 {
            let mut log = EventLog::with_limit(&temp.0, 350).unwrap();
            for _ in 0..10 {
                log.record("running", 0).unwrap();
            }
        }
        assert_eq!(fs::read_dir(&temp.0).unwrap().count(), 2);
        for entry in fs::read_dir(&temp.0).unwrap() {
            let p = entry.unwrap().path();
            assert!(p.metadata().unwrap().len() <= 350);
            for line in fs::read_to_string(p).unwrap().lines() {
                assert!(line.contains("event=running code=0"));
            }
        }
    }

    #[test]
    fn injected_newlines_and_oversized_events_do_not_change_log() {
        let temp = Temp::new();
        let mut log = EventLog::with_limit(&temp.0, 350).unwrap();
        log.record("starting", 0).unwrap();
        let before = fs::read(temp.0.join("events.log")).unwrap();
        assert!(log.record("running\nevent=fake", 0).is_err());
        assert!(log.record("", 0).is_err());
        assert!(log.record(&"a".repeat(65), 0).is_err());
        assert_eq!(before, fs::read(temp.0.join("events.log")).unwrap());
    }

    #[test]
    fn oversized_existing_log_is_preserved_and_not_rotated() {
        let temp = Temp::new();
        let original = vec![b'x'; 351];
        fs::write(temp.0.join("events.log"), &original).unwrap();
        assert!(EventLog::with_limit(&temp.0, 350).is_err());
        assert_eq!(fs::read(temp.0.join("events.log")).unwrap(), original);
        assert!(!temp.0.join("events.previous.log").exists());
    }
}
